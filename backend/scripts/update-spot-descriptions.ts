async function main() {
  const spots = await prisma.spot.findMany({
    where: {
      city: {
        in: ['北京', '北京市', '上海', '上海市', '广州', '广州市', '深圳', '深圳市', '成都', '成都市', '厦门', '厦门市'],
      },
    },
    select: {
      id: true,
      name: true,
      description: true,
    },
  });

  console.log(`找到 ${spots.length} 个景点需要更新描述`);

  let updated = 0;
  for (const spot of spots) {
    const description = SPOT_DESCRIPTIONS[spot.name];
    if (description && (!spot.description || spot.description.length < 50)) {
      await prisma.spot.update({
        where: { id: spot.id },
        data: { description },
      });
      updated++;
      console.log(`✓ 更新: ${spot.name}`);
    }
  }

  console.log(`\n完成! 共更新 ${updated} 个景点描述`);
}

main()
  .catch(console.error)
  .finally(() => prisma.$disconnect());
