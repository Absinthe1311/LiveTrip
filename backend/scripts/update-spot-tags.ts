async function main() {
  const spots = await prisma.spot.findMany({
    select: {
      id: true,
      name: true,
      category: true,
    },
  });

  console.log(`找到 ${spots.length} 个景点`);

  let updated = 0;
  for (const spot of spots) {
    let newTags: string[] = [];
    
    // 1. 处理原有标签
    if (spot.category) {
      const oldTags = spot.category.split(';').map(t => t.trim()).filter(t => t);
      
      for (const tag of oldTags) {
        // 检查是否有映射
        const mappedTags = TAG_MAPPING[tag] || TAG_MAPPING[spot.category];
        if (mappedTags) {
          newTags.push(...mappedTags);
        } else if (!tag.includes('科教文化') && !tag.includes('风景名胜;风景名胜') && tag !== '风景名胜') {
          // 保留其他标签，但去除同质化标签
          newTags.push(tag);
        }
      }
    }
    
    // 2. 补充景点特定标签
    const supplementTags = SPOT_TAG_SUPPLEMENT[spot.name];
    if (supplementTags) {
      newTags = supplementTags; // 使用补充标签替换原有标签
    }
    
    // 3. 去重
    newTags = Array.from(new Set(newTags));
    
    // 4. 限制最多3个标签
    newTags = newTags.slice(0, 3);
    
    // 5. 更新数据库
    if (newTags.length > 0) {
      const newCategory = newTags.join(';');
      if (newCategory !== spot.category) {
        await prisma.spot.update({
          where: { id: spot.id },
          data: { category: newCategory },
        });
        updated++;
        console.log(`✓ 更新: ${spot.name} -> ${newCategory}`);
      }
    }
  }

  console.log(`\n完成! 共更新 ${updated} 个景点标签`);
}

main()
  .catch(console.error)
  .finally(() => prisma.$disconnect());
